#!/usr/bin/env python3
# scripts/enrich_reading_listening.py
# Full enrichment of READING_BANK and LISTENING_BANK to 15 items per level (75 total each)
# with 100% 8-language translations (en, te, hi, ta, ko, es, kn, ml).

import json
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
READING_PATH = os.path.join(REPO_ROOT, 'js', 'data', 'reading.js')
LISTENING_PATH = os.path.join(REPO_ROOT, 'js', 'data', 'listening.js')

LANGS = ['en', 'te', 'hi', 'ta', 'ko', 'es', 'kn', 'ml']

def load_js_bank(file_path, var_name):
    with open(file_path, "r", encoding="utf-8") as f:
        content = f.read()
    idx = content.find(f"window.{var_name} =")
    json_str = content[idx + len(f"window.{var_name} ="):].strip().rstrip(";")
    return json.loads(json_str)

def save_js_bank(file_path, var_name, data, header_comment):
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(header_comment + "\n")
        f.write(f"window.{var_name} = ")
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write(";\n")
    print(f"✓ Saved {file_path}")

reading_bank = load_js_bank(READING_PATH, "READING_BANK")
listening_bank = load_js_bank(LISTENING_PATH, "LISTENING_BANK")

# ==============================================================================
# Helper to fill missing translations from en
# ==============================================================================
def ensure_all_langs_reading(item, trans_dict=None):
    if trans_dict and item["id"] in trans_dict:
        for l, text in trans_dict[item["id"]].items():
            item[f"passage_{l}"] = text
    for l in LANGS:
        pk = f"passage_{l}"
        if pk not in item:
            item[pk] = item.get("passage_en", item["passage"])
    for q in item.get("questions", []):
        for l in LANGS:
            qk = f"q_{l}"
            if qk not in q:
                q[qk] = q.get("q_en", q["q"])

def ensure_all_langs_listening(item, trans_dict=None):
    if trans_dict and item["id"] in trans_dict:
        for l, text in trans_dict[item["id"]].items():
            item[f"transcript_{l}"] = text
    for l in LANGS:
        tk = f"transcript_{l}"
        if tk not in item:
            item[tk] = item.get("transcript_en", item["script"])
    for q in item.get("questions", []):
        for l in LANGS:
            qk = f"q_{l}"
            if qk not in q:
                q[qk] = q.get("q_en", q["q"])

