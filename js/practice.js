    function t(key, vars) {
        const code = (typeof LANG_PACK_CODES !== 'undefined' && typeof player !== 'undefined') ? LANG_PACK_CODES[player.nativeLanguage] : null;
        let s = (code && window.UI_I18N && window.UI_I18N[code] && window.UI_I18N[code][key]) || STRINGS[key] || key;
        if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
        return s;
    }

    function loadScript(src, cb) {
        if (loadedSrc[src]) { cb(); return; }
        const s = document.createElement('script');
        s.src = src;
        s.onload = () => { loadedSrc[src] = true; cb(); };
        s.onerror = () => { console.log('practice: failed to load', src); cb(); };
        document.head.appendChild(s);
    }

    // Award XP/gold on the same level-up curve as the arena.
    // ponytail: mirrors the arena's inline level-up (checkBattleResolution); a
    // 6-line dup beats refactoring that hot path just to share it.
    function award(xp, gold) {
        if (typeof player === 'undefined') return;
        player.xp += xp; player.gold += gold;
        while (player.xp >= player.maxXp) {
            player.level++; player.xp -= player.maxXp;
            player.maxHp += 20; player.hp = player.maxHp;
            player.maxXp = Math.round(player.maxXp * 1.5);
        }
        if (typeof updateHUDDisplays === 'function') updateHUDDisplays();
        if (typeof saveGameData === 'function') saveGameData();
    }

    // random n items (for exam variety across attempts)
    function pickN(arr, n) {
        return [...arr].sort(() => Math.random() - 0.5).slice(0, n);
    }

    function levelPills(current, onPick) {
        const wrap = document.createElement('div');
        wrap.className = 'practice-levels';
        LEVELS.forEach(lv => {
            const b = document.createElement('button');
            b.type = 'button';
            b.className = 'practice-level' + (lv === current ? ' active' : '');
            b.textContent = lv;
            b.onclick = () => onPick(lv);
            wrap.appendChild(b);
        });
        return wrap;
    }

    // Render MC questions into `container`. `answer` is the index of the correct
    // option. Calls onDone(correctCount) once every question is answered.
    function renderQuestions(container, questions, onDone, parentItem) {
        let answered = 0, correct = 0;
        questions.forEach((qq, qi) => {
            const card = document.createElement('div');
            card.className = 'practice-q';
            const qt = document.createElement('div');
            qt.className = 'practice-q-text';
            qt.textContent = (qi + 1) + '. ' + qq.q;
            card.appendChild(qt);
            const code = (typeof LANG_PACK_CODES !== 'undefined' && typeof player !== 'undefined') ? LANG_PACK_CODES[player.nativeLanguage] : null;
            const nativeQ = (code && qq['q_' + code]) || qq.q_en;
            if (nativeQ) {
                const en = document.createElement('div');
                en.className = 'practice-q-en';
                en.textContent = nativeQ;
                card.appendChild(en);
            }
            const opts = document.createElement('div');
            opts.className = 'practice-opts';
            let locked = false;

            const explBox = document.createElement('div');
            explBox.className = 'practice-explanation';
            explBox.style.display = 'none';

            qq.options.forEach((opt, oi) => {
                const ob = document.createElement('button');
                ob.type = 'button';
                ob.className = 'practice-opt';
                ob.textContent = opt;
                ob.onclick = () => {
                    if (locked) return;
                    locked = true;
                    answered++;
                    const isRight = (oi === qq.answer);
                    if (isRight) correct++;
                    else ob.classList.add('wrong');
                    opts.children[qq.answer].classList.add('right');

                    // Show Explanation Card
                    explBox.style.display = 'block';
                    explBox.style.marginTop = '12px';
                    explBox.style.padding = '12px 14px';
                    explBox.style.borderRadius = '8px';
                    explBox.style.fontSize = '0.85rem';
                    explBox.style.lineHeight = '1.45';
                    explBox.style.border = isRight ? '1px solid rgba(32,191,107,0.3)' : '1px solid rgba(255,118,117,0.3)';
                    explBox.style.background = isRight ? 'rgba(32,191,107,0.08)' : 'rgba(255,118,117,0.08)';

                    const correctOptText = qq.options[qq.answer];
                    const explText = (code && qq['explanation_' + code]) || qq.explanation_en || qq.explanation ||
                        `Correct answer: "${correctOptText}". This option directly matches the authentic details in the passage.`;

                    explBox.innerHTML = `
                        <div style="font-weight: 700; color: ${isRight ? 'var(--accent-teal, #20bf6b)' : 'var(--accent-pink, #ff7675)'}; margin-bottom: 4px; display: flex; align-items: center; gap: 6px;">
                            <i class="fa-solid ${isRight ? 'fa-circle-check' : 'fa-circle-xmark'}"></i>
                            <span>${isRight ? (t('p.correct') || 'Correct! (正解)') : (t('p.incorrect') || 'Incorrect')}</span>
                        </div>
                        <div style="color: #ddd;">${explText}</div>
                    `;

                    if (answered === questions.length && onDone) onDone(correct);
                };
                opts.appendChild(ob);
            });
            card.appendChild(opts);
            card.appendChild(explBox);
            container.appendChild(card);
        });
    }

