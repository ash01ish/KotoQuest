    function buildVocabSection(lv, count) {
        // reuse the arena's procedural vocab/reading questions; normalise answer to index
        if (typeof generateProceduralQuestions !== 'function') return [];
        const raw = generateProceduralQuestions(lv, count) || [];
        return raw.filter(q => q && q.options && q.options.length).map(q => ({
            q: q.q,
            options: q.options,
            answer: Math.max(0, q.options.indexOf(q.answer))
        }));
    }

    function runExam(lv) {
        const readingBank = (window.READING_BANK || {})[lv] || [];
        const listeningBank = (window.LISTENING_BANK || {})[lv] || [];
        const sections = [
            { key: 'Language Knowledge', type: 'vocab', questions: buildVocabSection(lv, 10) },
            { key: 'Reading', type: 'reading', items: pickN(readingBank, 2) },
            { key: 'Listening', type: 'listening', items: pickN(listeningBank, 2) }
        ];

        const root = document.getElementById('exam');
        root.innerHTML = '';
        const card = document.createElement('div');
        card.className = 'glass-card';
        root.appendChild(card);

        // Timer bar
        const bar = document.createElement('div');
        bar.className = 'exam-bar';
        const timeEl = document.createElement('span');
        timeEl.className = 'exam-timer';
        bar.appendChild(timeEl);
        const submitBtn = document.createElement('button');
        submitBtn.type = 'button';
        submitBtn.className = 'btn exam-submit';
        submitBtn.textContent = t('p.submit');
        bar.appendChild(submitBtn);
        card.appendChild(bar);

        const secLabel = (k) => t(k === 'Language Knowledge' ? 'p.secLK' : k === 'Reading' ? 'p.secReading' : 'p.secListening');
        // track score per section: {section: {correct, total}}
        const score = {};
        sections.forEach(s => { score[s.key] = { correct: 0, total: 0 }; });

        // record answers: for each rendered question, store correctness getter
        const graders = [];

        sections.forEach(sec => {
            const secEl = document.createElement('div');
            secEl.className = 'exam-section';
            const h = document.createElement('div');
            h.className = 'exam-section-title';
            h.textContent = secLabel(sec.key);
            secEl.appendChild(h);

            if (sec.type === 'vocab') {
                sec.questions.forEach(q => graders.push(mkGrader(secEl, sec.key, q)));
            } else {
                (sec.items || []).forEach(item => {
                    if (sec.type === 'reading') {
                        const p = document.createElement('div');
                        p.className = 'reading-passage';
                        p.textContent = item.passage;
                        secEl.appendChild(p);
                    } else {
                        const play = document.createElement('button');
                        play.type = 'button';
                        play.className = 'btn listening-play';
                        play.innerHTML = '<i class="fa-solid fa-play"></i> ' + t('p.playAudio');
                        play.onclick = () => { if (typeof speakJapanese === 'function') speakJapanese(item.script, 0.9); };
                        secEl.appendChild(play);
                    }
                    (item.questions || []).forEach(q => graders.push(mkGrader(secEl, sec.key, q)));
                });
            }
            card.appendChild(secEl);
        });

        // Grader: renders a question, returns {section, isCorrect()}.
        function mkGrader(parent, sectionKey, q) {
            score[sectionKey].total++;
            const box = document.createElement('div');
            box.className = 'practice-q';
            const qt = document.createElement('div');
            qt.className = 'practice-q-text';
            qt.textContent = q.q;
            box.appendChild(qt);
            const opts = document.createElement('div');
            opts.className = 'practice-opts';
            let chosen = -1;
            q.options.forEach((opt, oi) => {
                const ob = document.createElement('button');
                ob.type = 'button';
                ob.className = 'practice-opt';
                ob.textContent = opt;
                ob.onclick = () => {
                    chosen = oi;
                    opts.querySelectorAll('.practice-opt').forEach(x => x.classList.remove('chosen'));
                    ob.classList.add('chosen');
                };
                opts.appendChild(ob);
            });
            box.appendChild(opts);
            parent.appendChild(box);
            return { sectionKey, opts, q, isCorrect: () => chosen === q.answer, reveal: () => {
                opts.children[q.answer] && opts.children[q.answer].classList.add('right');
            } };
        }

        // Timer: ~1 min per question, min 5 min.
        let remaining = Math.max(300, graders.length * 45);
        const fmt = (s) => String(Math.floor(s / 60)).padStart(2, '0') + ':' + String(s % 60).padStart(2, '0');
        timeEl.textContent = '⏱ ' + fmt(remaining);
        let done = false;
        const tick = setInterval(() => {
            remaining--;
            timeEl.textContent = '⏱ ' + fmt(remaining);
            if (remaining <= 0) finish();
        }, 1000);

        function finish() {
            if (done) return;
            done = true;
            clearInterval(tick);
            graders.forEach(g => {
                if (g.isCorrect()) score[g.sectionKey].correct++;
                g.reveal();
            });
            // scale each section to /60
            let overall = 0; const lines = []; let sectionalFail = false;
            sections.forEach(s => {
                const sc = score[s.key];
                const scaled = sc.total ? Math.round((sc.correct / sc.total) * 60) : 0;
                overall += scaled;
                if (scaled < 19) sectionalFail = true;
                lines.push(`${secLabel(s.key)}: ${scaled}/60${scaled < 19 ? '  ✕ ' + t('p.below19') : ''}`);
            });
            const passed = overall >= 100 && !sectionalFail;
            award(passed ? 80 : Math.round(overall / 3), passed ? 40 : 10);

            const res = document.createElement('div');
            res.className = 'exam-result ' + (passed ? 'pass' : 'fail');
            res.innerHTML = `<div class="exam-verdict">${passed ? t('p.pass') : t('p.notYet')} — ${overall}/180</div>`
                + lines.map(l => `<div class="exam-line">${l}</div>`).join('')
                + `<div class="exam-note">${t('p.passNote')}</div>`;

            // Social Brag / Viral Share Tray
            const shareText = `🏯 I scored ${overall}/180 (${passed ? 'PASS 🎉' : 'NOT YET 💪'}) on the JLPT ${lv} Mock Exam on KotoQuest!\n`
                + lines.map(l => `• ${l}`).join('\n') + '\n\n'
                + `Free, offline JLPT study academy: https://kotoquest.pages.dev/#exam?level=${lv}`;

            const shareTray = document.createElement('div');
            shareTray.className = 'share-tray';
            shareTray.innerHTML = `
                <span class="share-label"><i class="fa-solid fa-share-nodes"></i> Share:</span>
                ${passed ? '<button type="button" class="share-btn share-btn-primary" id="btn-claim-cert"><i class="fa-solid fa-award"></i> Claim Certificate</button>' : ''}
                <button type="button" class="share-btn share-btn-primary" id="btn-share-native"><i class="fa-solid fa-share-from-square"></i> Share Score</button>
                <a class="share-btn share-btn-wa" href="https://api.whatsapp.com/send?text=${encodeURIComponent(shareText)}" target="_blank" rel="noopener"><i class="fa-brands fa-whatsapp"></i> WhatsApp</a>
                <a class="share-btn share-btn-x" href="https://twitter.com/intent/tweet?text=${encodeURIComponent(shareText)}" target="_blank" rel="noopener"><i class="fa-brands fa-x-twitter"></i> Post</a>
                <button type="button" class="share-btn share-btn-copy" id="btn-share-copy"><i class="fa-solid fa-copy"></i> Copy</button>
            `;
            res.appendChild(shareTray);

            const btnCert = shareTray.querySelector('#btn-claim-cert');
            if (btnCert) {
                btnCert.onclick = () => {
                    if (typeof window.openCertificateModal === 'function') {
                        window.openCertificateModal();
                    } else {
                        window.location.hash = '#certificate';
                    }
                };
            }

            const btnNative = shareTray.querySelector('#btn-share-native');
            if (btnNative) {
                btnNative.onclick = () => {
                    if (navigator.share) {
                        navigator.share({
                            title: `KotoQuest - JLPT ${lv} Mock Exam`,
                            text: shareText,
                            url: `https://kotoquest.pages.dev/#exam?level=${lv}`
                        }).catch(() => {});
                    } else {
                        navigator.clipboard.writeText(shareText);
                        if (typeof window.showToast === 'function') window.showToast('Score copied to clipboard!');
                    }
                };
            }
            const btnCopy = shareTray.querySelector('#btn-share-copy');
            if (btnCopy) {
                btnCopy.onclick = () => {
                    navigator.clipboard.writeText(shareText);
                    if (typeof window.showToast === 'function') window.showToast('Score copied to clipboard!');
                };
            }

            card.insertBefore(res, card.children[1]);
            const retry = document.createElement('button');
            retry.type = 'button';
            retry.className = 'btn';
            retry.style.marginTop = '14px';
            retry.textContent = t('p.backExam');
            retry.onclick = () => renderExam(lv);
            card.appendChild(retry);
            res.scrollIntoView({ block: 'start', behavior: 'smooth' });
        }
        submitBtn.onclick = finish;
    }

    // Lazy-render each module the first time its tab is opened (and on resume).
    const RENDERERS = { reading: renderReading, listening: renderListening, exam: renderExam };
    const rendered = {};
    function ensureRendered(tab, level) {
        if (!RENDERERS[tab]) return;
        rendered[tab] = true;
        RENDERERS[tab](level);
    }
    // Allow external callers to render a practice tab directly with an optional level
    window.renderPracticeTab = function(tab, level) {
        if (RENDERERS[tab]) {
            ensureRendered(tab, level);
        }
    };
    // Allow external callers (e.g. applyNativeLanguageNuances in app.js) to re-render
    // practice modules in the newly selected language.
    window.refreshPracticeModules = function() {
        for (const tab in rendered) {
            if (rendered[tab] && RENDERERS[tab]) {
                RENDERERS[tab]();
            }
        }
    };

    document.addEventListener('DOMContentLoaded', () => {
        const nav = document.getElementById('main-nav');
        if (nav) nav.addEventListener('click', (e) => {
            const t = e.target.closest('.nav-tab');
            if (t) ensureRendered(t.getAttribute('data-tab'));
        });
        // resume: if the app restored one of our tabs, render it
        if (typeof player !== 'undefined' && player.lastTab && RENDERERS[player.lastTab]) {
            ensureRendered(player.lastTab);
        }
    });
